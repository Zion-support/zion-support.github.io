def main():
    services = load_services()
    print(f'Catalog: {len(services)} services')

    # Determine which services need docs artifacts
    # Read progress to know the batch range
    last_processed = 0
    if os.path.exists(PROGRESS_FILE):
        try:
            with open(PROGRESS_FILE, 'r') as f:
                last_processed = int(f.read().strip())
        except (ValueError, IOError):
            pass

    # The batch that was just processed: services[last_processed-50:last_processed]
    # Since progress was updated to 18970, the batch was [18920:18970]
    batch_start = max(0, last_processed - 50)
    batch_services = services[batch_start:last_processed]
    print(f'Processing batch: services[{batch_start}:{last_processed}] ({len(batch_services)} services)')

    generated = 0
    skipped = 0
    for svc in batch_services:
        service_id = svc.get('id', 'unknown-service')
        if not service_id:
            continue

        safe = safe_service_id_from_page(service_id)
        html_path = os.path.join(DOCS_DIR, safe, 'index.html')
        page_txs_path = os.path.join(SERVICES_DIR, service_id, 'page.tsx')

        if os.path.exists(html_path):
            print(f'  [⏭]  docs artifact already exists: {safe}')
            skipped += 1
            continue

        if not os.path.exists(page_txs_path):
            print(f'  [✗]  page.tsx not found: {service_id}')
            continue

        with open(page_txs_path, 'r') as f:
            page_content = f.read()

        html_content = generate_html(service_id, svc, page_content)
        os.makedirs(os.path.dirname(html_path), exist_ok=True)
        with open(html_path, 'w') as f:
            f.write(html_content)
        print(f'  [📄] Generated docs artifact: {safe}')
        generated += 1

    print(f'Total docs artifacts generated: {generated}')
    print(f'Skipped (already existed): {skipped}')


if __name__ == '__main__':
    main()
