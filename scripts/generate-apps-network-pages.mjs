// Dedicated sitemap for the generated app pages, referenced from sitemap.xml.
const sitemapUrls = [];
for (const app of APPS) {
  for (const lang of LANGS) {
    sitemapUrls.push(`  <url><loc>${pageUrl(lang, app.slug)}</loc><changefreq>weekly</changefreq><priority>0.7</priority></url>`);
  }
}
for (const lang of LANGS) {
  sitemapUrls.push(`  <url><loc>${lang.prefix ? `${SITE}/${lang.prefix}` : SITE}/apps-network/</loc><changefreq>weekly</changefreq><priority>0.8</priority></url>`);
}
write(
  path.join(PUBLIC, 'apps-network-sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by scripts/generate-apps-network-pages.mjs — do not edit by hand. -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${sitemapUrls.join('\n')}\n</urlset>\n`
);

process.stdout.write(`Wrote ${written.length} app pages + apps-network-sitemap.xml\n`);
