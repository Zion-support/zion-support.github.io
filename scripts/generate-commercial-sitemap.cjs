#!/usr/bin/env node
// generate-commercial-sitemap.cjs
// Rebuild public/sitemap-0.xml + public/sitemap.xml from real, indexable pages.
//
// Rules:
// - Do not invent URLs: only emit paths that exist as public/**/index.html
// - Skip any page whose meta robots contains noindex (stubs / placeholders).
//   Google ignores noindex URLs in a sitemap and may treat their presence as a
//   crawl-budget signal; the old fat sitemap shipped ~55k URLs of which the
//   majority were 404s or noindex service stubs.
// - Skip /services/* hashed placeholders entirely (all noindex by design).
// - FIELD-SERVICES LOCK: hub + brazil only — never walk country leaves.
// - /pricing/ stays out (PL-2 / #71192).
// - Satellite sitemaps (apps-network, apps, editorial) are generated by their
//   own scripts and are listed in the index only when the file exists.
//
// Usage: node scripts/generate-commercial-sitemap.cjs

const fs = require('fs');
const path = require('path');

const SITE = 'https://ziontechgroup.com';
const ROOT = process.cwd();
const PUBLIC = path.join(ROOT, 'public');

// Required after content restore #71308
const CORE = [
  '/',
  '/about/',
  '/solutions/',
  '/managed-it-services/',
  '/ai-consulting-services/',
  '/finops-consulting/',
  '/autonomous-ai-agents/',
  '/blog/',
  '/plans/',
  '/discovery/',
  '/enterprise/',
  '/case-studies/',
  '/contact/',
  '/services/',
  '/field-services/',
];

// Already-present public/ pages (live 200). Not country leaves. Not invented.
// /pricing/ omitted on purpose. /public-roadmap/ and /status-page/ are noindex
// and are therefore not listed here.
const EXTRA = [
  '/field-services/brazil/',
  '/field-services-brazil/',
  '/free-consultation/',
  '/telegram/',
  '/use-cases/',
  '/industries/healthcare/',
  '/industries/insurance/',
  '/industries/legal/',
  '/ai-department/',
];

// Top-level public/ directories covered by satellite sitemaps, or not pages.
const SKIP_TOP_DIRS = new Set([
  'services',
  'apps',
  'apps-network',
  '404',
  '_not-found',
  'node_modules',
  'data',
  'api',
  '__next',
]);

// Satellite sitemaps listed in the index when present (relative to public/).
const SATELLITES = [
  'apps-network-sitemap.xml',
  'sitemap-apps-network-en.xml',
  'sitemap-apps-network-pt-BR.xml',
  'sitemap-apps-network-es.xml',
  'sitemap-apps-network-fr.xml',
  'sitemap-apps-network-de.xml',
  'apps/apps-sitemap.xml',
  'sitemap-editorial.xml',
];

function publicFileFor(urlPath) {
  if (urlPath === '/') return path.join(PUBLIC, 'index.html');
  return path.join(PUBLIC, urlPath.replace(/^\//, ''), 'index.html');
}

function lastmodFor(file) {
  try {
    return fs.statSync(file).mtime.toISOString().split('T')[0];
  } catch {
    return new Date().toISOString().split('T')[0];
  }
}

function hashedServiceSlug(name) {
  return /-[0-9a-f]{6,}$/i.test(name);
}

// True when the page carries <meta name="robots" content="...noindex...">.
function metaRobotsNoindex(html) {
  const tags = html.match(/<meta\b[^>]*>/gi) || [];
  for (const tag of tags) {
    const name = tag.match(/name=["']([^"']+)["']/i);
    const content = tag.match(/content=["']([^"']*)["']/i);
    if (name && content && name[1].toLowerCase() === 'robots' && /noindex/i.test(content[1])) {
      return true;
    }
  }
  return false;
}

function isIndexableFile(file) {
  try {
    const head = fs.readFileSync(file, 'utf8').slice(0, 16384);
    return !metaRobotsNoindex(head);
  } catch {
    return false;
  }
}

function add(pages, seen, urlPath, priority, changefreq, opts = {}) {
  if (seen.has(urlPath)) return false;
  const file = publicFileFor(urlPath);
  if (!fs.existsSync(file)) return false;
  if (!isIndexableFile(file)) {
    if (opts.required) {
      throw new Error(`required page is noindex or unreadable: ${urlPath} (${file})`);
    }
    return false;
  }
  seen.add(urlPath);
  pages.push({
    loc: urlPath === '/' ? `${SITE}/` : `${SITE}${urlPath}`,
    lastmod: lastmodFor(file),
    priority,
    changefreq,
  });
  return true;
}

function collect() {
  const pages = [];
  const seen = new Set();

  add(pages, seen, '/', '1.0', 'daily', { required: true });
  for (const p of CORE) {
    if (p === '/') continue;
    add(pages, seen, p, '0.8', 'weekly', { required: true });
  }

  // Blog: only indexable posts (most historical posts are noindex stubs).
  const blogDir = path.join(PUBLIC, 'blog');
  if (fs.existsSync(blogDir)) {
    for (const entry of fs.readdirSync(blogDir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      add(pages, seen, `/blog/${entry.name}/`, '0.6', 'weekly');
    }
  }

  for (const p of EXTRA) add(pages, seen, p, '0.5', 'weekly');

  // Remaining indexable top-level pages (includes /en/ /pt/ /es/ /fr/ /de/).
  for (const entry of fs.readdirSync(PUBLIC, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    if (SKIP_TOP_DIRS.has(entry.name)) continue;
    if (entry.name.startsWith('.') || entry.name.startsWith('_')) continue;
    add(pages, seen, `/${entry.name}/`, '0.6', 'weekly');
  }

  pages.sort((a, b) => a.loc.localeCompare(b.loc));
  return pages;
}

function buildUrlset(pages) {
  const rows = pages.map(
    (p) =>
      `<url><loc>${p.loc}</loc><lastmod>${p.lastmod}</lastmod><changefreq>${p.changefreq}</changefreq><priority>${p.priority}</priority></url>`
  );
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Commercial sitemap-0: real, indexable pages only. No hashed /services/* orphans, no noindex stubs. -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...rows,
    '</urlset>',
    '',
  ].join('\n');
}

function buildIndex() {
  const rows = [`<sitemap><loc>${SITE}/sitemap-0.xml</loc></sitemap>`];
  for (const rel of SATELLITES) {
    if (fs.existsSync(path.join(PUBLIC, rel))) {
      rows.push(`<sitemap><loc>${SITE}/${rel}</loc></sitemap>`);
    }
  }
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...rows,
    '</sitemapindex>',
    '',
  ].join('\n');
}

function writeBoth(dir, pages) {
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'sitemap-0.xml'), buildUrlset(pages));
  fs.writeFileSync(path.join(dir, 'sitemap.xml'), buildIndex());
}

function assertRequired(pages) {
  const locs = new Set(pages.map((p) => p.loc));
  const missing = [];
  for (const p of CORE) {
    const loc = p === '/' ? `${SITE}/` : `${SITE}${p}`;
    if (!locs.has(loc)) missing.push(p);
  }
  if (missing.length) {
    throw new Error(`sitemap-0 missing required public pages: ${missing.join(', ')}`);
  }
  const hashed = pages.filter((p) => {
    const m = p.loc.match(/\/services\/([^/]+)\/?$/);
    return m && hashedServiceSlug(m[1]);
  });
  if (hashed.length) {
    throw new Error(`sitemap-0 must not include hashed /services/*: ${hashed[0].loc}`);
  }
  const fieldLeaves = pages.filter((p) => {
    const u = p.loc.replace(SITE, '');
    if (u === '/field-services/' || u === '/field-services/brazil/' || u === '/field-services-brazil/') {
      return false;
    }
    return u.startsWith('/field-services/');
  });
  if (fieldLeaves.length) {
    throw new Error(`FIELD-SERVICES LOCK: unexpected leaf ${fieldLeaves[0].loc}`);
  }
}

function main() {
  const pages = collect();
  assertRequired(pages);
  writeBoth(PUBLIC, pages);
  const outDir = path.join(ROOT, 'out');
  if (fs.existsSync(outDir)) writeBoth(outDir, pages);
  console.log(`sitemap-0.xml: ${pages.length} indexable urls`);
  console.log(`sitemap.xml: sitemapindex -> ${SATELLITES.length + 1} sitemaps (sitemap-0 + satellites)`);
  return pages;
}

if (require.main === module) main();

module.exports = { collect, writeBoth, main, CORE, EXTRA, metaRobotsNoindex, isIndexableFile };
